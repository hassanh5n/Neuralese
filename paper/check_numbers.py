"""Check every number in paper/sections and paper/appendix against its source in docs/neuralese-paper-log.md.

Each line of prose that holds a number must end with a comment naming its source:
  % C23.15 C23.8        claim-ledger rows (section 2); "C21.7-8" covers C21.7 and C21.8
  % PR(Exp 22 P1, P3)   rows of the pre-registration margins table (section 3), matched by the start of the first cell
  % SETUP               method, setup and version text (sections 1, 3, 4, 5 and 10 of the log)
  % CITE(key)           a number reported by another paper; the key must be in refs.bib
A number passes if the same value (sign ignored; 47% = 0.47) appears in a named source. Numbers that are names or
structure are skipped: Exp/Q/P/E/A labels, refs, labels, citations, file names, 50/50, 95% CI, and the values 0 and 1.
Lines without a comment that still hold a number are reported as untagged.
Figure and table files in figures/ are generated by scripts and checked cell by cell by verify_robustness.py.
Run from anywhere: python paper/check_numbers.py   (exit code 1 on any mismatch or untagged number)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LOG = (ROOT.parent / "docs" / "neuralese-paper-log.md").read_text(encoding="utf-8")
NUM = re.compile(r"\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?(?:e-?\d+)?")


def nums(text):
    text = text.replace("\u2212", "-")
    text = re.sub(r"(\d+(?:\.\d+)?)\s*\\times\s*10\^\{(-?\d+)\}", r"\1e\2", text)
    return [float(n.replace(",", "")) for n in NUM.findall(text)]


def section(n):
    m = re.search(rf"^## {n}\. .*?(?=^## {n + 1}\. )", LOG, re.S | re.M)
    return m.group(0)


# Ledger rows: id -> claim and value text.
LEDGER = {}
for line in section(2).replace("\\|", "¦").splitlines():
    m = re.match(r"\|\s*(C\d+)\.(\d+)(?:[\u2013-](\d+))?\s*\|(.*?)\|(.*?)\|", line)
    if m:
        lo, hi = int(m.group(2)), int(m.group(3) or m.group(2))
        for k in range(lo, hi + 1):
            LEDGER[f"{m.group(1)}.{k}"] = m.group(4) + " " + m.group(5)
PREREG = [l for l in section(3).splitlines() if l.startswith("| ") and not l.startswith("| Prediction")]
SETUP = section(1) + section(3) + section(4) + section(5) + section(10)
BIB = (ROOT / "refs.bib").read_text(encoding="utf-8")


def match(x, pool):
    return any(abs(x - y) < 1e-9 or abs(x - 100 * y) < 1e-9 or abs(100 * x - y) < 1e-9 for y in pool)


STRIP = [r"\\setlength\{[^}]*\}\{[^}]*\}", r"\\\\\[[\d.]+pt\]", r"\\multicolumn\{\d+\}", r"\\cmidrule(?:\([a-z]*\))?\{[\d-]+\}", r"\\texttt\{[^}]*\}", r"\\begin\{(?:itemize|enumerate)\}\[[^\]]*\]", r"\\(?:cref|Cref|ref|label|citep|citet|cite|input|includegraphics|url|href)\*?(?:\[[^\]]*\])?\{[^}]*\}",
         r"\\begin\{minipage\}\[[a-z]\]\{[\d.]+in\}", r"\\(?:hspace|vspace)\*?\{[^}]*\}", r"\[[\d.]+pt\]",
         r"Exp~?\s?\d+", r"\b[QPEA]\d\b", r"\b[A-Z][a-z]*~?\d+\b(?= *[a-z]*\})", r"50/50", r"95\\?%", r"\\section|\\subsection",
         r"\b(?:fig|tab)A?\d\w*\.(?:pdf|tex)", r"GSM8K", r"^\s*\((\d)\)", r"\((\d)\) (?=[A-Z])"]
bad, untagged, checked = [], [], 0
for f in sorted(list((ROOT / "sections").glob("*.tex")) + list((ROOT / "appendix").glob("*.tex"))):
    for i, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
        if line.lstrip().startswith("%"):
            continue
        parts = re.split(r"(?<!\\)%", line, maxsplit=1)
        text, comment = parts[0], (parts[1] if len(parts) > 1 else "")
        for pat in STRIP:
            text = re.sub(pat, " ", text)
        values = [x for x in nums(text) if x not in (0.0, 1.0)]
        if not values:
            continue
        ids = re.findall(r"C\d+\.\d+(?:-\d+)?", comment)
        pool = []
        for cid in ids:
            base, rest = cid.split(".")
            lo, _, hi = rest.partition("-")
            for k in range(int(lo), int(hi or lo) + 1):
                key = f"{base}.{k}"
                if key not in LEDGER:
                    bad.append(f"{f.name}:{i}: unknown ledger id {key}")
                pool += nums(LEDGER.get(key, ""))
        for group in re.findall(r"PR\(([^)]*)\)", comment):
            last = ""
            for name in [g.strip() for g in group.split(",")]:
                if re.fullmatch(r"P\d|A\d|E\d", name) and last:
                    name = last + " " + name
                last = name.rsplit(" ", 1)[0] if " " in name else ""
                rows = [r for r in PREREG if r[2:].startswith(name)]
                if not rows:
                    bad.append(f"{f.name}:{i}: no pre-registration row {name!r}")
                pool += [x for r in rows for x in nums(r)]
        if "SETUP" in comment:
            pool += nums(SETUP)
        cites = re.findall(r"CITE\(([^)]*)\)", comment)
        for c in cites:
            for key in c.split(","):
                if "{" + key.strip() + "," not in BIB:
                    bad.append(f"{f.name}:{i}: CITE key {key.strip()!r} not in refs.bib")
        if cites and not (ids or "PR(" in comment or "SETUP" in comment):
            continue  # numbers from another paper: cited, not checked against our ledger
        if not (ids or "PR(" in comment or "SETUP" in comment):
            untagged.append(f"{f.name}:{i}: {line.strip()[:110]}")
            continue
        for x in values:
            checked += 1
            if not match(abs(x), [abs(y) for y in pool]):
                bad.append(f"{f.name}:{i}: {x:g} not in {comment.strip()}  |  {line.strip()[:90]}")

print(f"{checked} numbers checked against {len(LEDGER)} ledger rows")
for b in bad:
    print("MISMATCH", b)
for u in untagged:
    print("UNTAGGED", u)
print("ALL NUMBERS MATCH" if not (bad or untagged) else f"{len(bad)} mismatches, {len(untagged)} untagged lines")
sys.exit(1 if bad or untagged else 0)
